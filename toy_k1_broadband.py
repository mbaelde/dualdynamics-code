"""Toy K=1: BROADBAND (rather than pure-sinusoidal) parametric forcing.

`toy_k1_parametric.py` established, for sinusoidal modulation of the sensitivity
c = dg/dtheta, that:
  - coherent modulation (eps_theta = eps_lam) never destabilizes, since the
    resonant forcing cancels at the principal tongue omega = 2*omega_0;
  - only mismatch destabilizes, with threshold |eps_lam - eps_theta| > 4*zeta;
  - this tolerance collapses as sqrt(eta_theta/eta_lambda).

Immediate objection from a reviewer: the cancellation uses omega^2/2 = 2*omega_0^2,
so it is EXACT at the resonance frequency and only there. A real non-stationary
CMDP does not have a spectrum reduced to one line: it has a density. Two
questions, and the paper only holds if both are answered well.

  Q1. Does the coherent cancellation survive broadband forcing centered on
      2*omega_0? For a detuned component omega = 2*omega_0*(1+delta), the
      forcing bracket equals (eps_lam - eps_theta)*omega_0^2 - 4*delta*eps_theta*omega_0^2:
      it no longer cancels. Coherent modulation therefore acquires a residual
      forcing proportional to the detuning. What remains to check is whether
      this residual, which is itself detuned from resonance, can beat the
      damping.

  Q2. Does the mismatch criterion survive, and in what form? The theoretical
      expectation is that the amplitude criterion becomes a SPECTRAL DENSITY
      criterion near 2*omega_0: at fixed modulation power, spreading the
      spectrum over a bandwidth B dilutes the density by 1/B, so the RMS
      amplitude threshold should grow as sqrt(B) once B exceeds the damping
      rate sigma = zeta*omega_0.

Method. The system is no longer periodic, the monodromy no longer exists. We
measure the top Lyapunov exponent of the random product of step matrices, by
iterating a renormalized vector at each step, over R independent realizations
run in parallel (numpy vectorization on the realization axis). The modulation
signal is generated by a rectangular spectral mask followed by irfft, which
gives exact control over the bandwidth and allows the degenerate "single
line" case (sine with random phase) as a control against Floquet.

Amplitude convention: eps here denotes the RMS value of the modulation, while
the periodic script spoke in peak amplitude. For a sine wave,
peak = sqrt(2) * RMS. Thresholds are therefore compared to h_crit / sqrt(2).

Operating point: identical to that of the periodic script
(eta_theta = 1e-3, eta_lambda = 1e-1), so that thresholds are directly
comparable.
"""

from __future__ import annotations

import numpy as np

from toy_k1_parametric import A_CURV, C_SENS, natural_mode

SEED = 20260821
ETA_T = 1e-3
ETA_L = 1e-1

T_STEPS = 200_000
N_REAL = 16
BURN = 40_000


def narrowband(
    t_steps: int,
    n_real: int,
    omega_c: float,
    bandwidth: float,
    rng: np.random.Generator,
) -> np.ndarray:
    """Rectangular-band signal [omega_c +- B/2], unit variance per realization.

    bandwidth <= 0 degenerates into a single spectral line, i.e. a sine wave
    with random phase: this is the limiting case that must reproduce Floquet.
    """
    freqs = 2.0 * np.pi * np.fft.rfftfreq(t_steps, d=1.0)
    if bandwidth <= 0.0:
        idx = np.array([int(np.argmin(np.abs(freqs - omega_c)))])
    else:
        idx = np.flatnonzero(np.abs(freqs - omega_c) <= 0.5 * bandwidth)
        if idx.size < 3:
            raise ValueError(f"under-resolved band: {idx.size} lines for B={bandwidth}")
    spec = np.zeros((freqs.size, n_real), dtype=complex)
    spec[idx] = rng.normal(size=(idx.size, n_real)) + 1j * rng.normal(size=(idx.size, n_real))
    s = np.fft.irfft(spec, n=t_steps, axis=0)
    return s / s.std(axis=0, keepdims=True)


def lyapunov(
    s: np.ndarray,
    eps_theta: float,
    eps_lam: float,
    eta_t: float = ETA_T,
    eta_l: float = ETA_L,
    a: float = A_CURV,
    c: float = C_SENS,
    burn: int = BURN,
) -> tuple[float, float]:
    """Top Lyapunov exponent per step: (mean, std) across realizations."""
    t_steps, n_real = s.shape
    x = np.ones(n_real)
    y = np.zeros(n_real)
    acc = np.zeros(n_real)
    for t in range(t_steps):
        st = s[t]
        c_t = c * (1.0 + eps_theta * st)
        c_l = c * (1.0 + eps_lam * st)
        xn = (1.0 - eta_t * a) * x - eta_t * c_t * y
        yn = eta_l * c_l * x + y
        nrm = np.sqrt(xn * xn + yn * yn)
        if t >= burn:
            acc += np.log(nrm)
        x = xn / nrm
        y = yn / nrm
    exps = acc / (t_steps - burn)
    return float(exps.mean()), float(exps.std())


def crossing(eps_grid: list[float], values: list[float]) -> float:
    """First zero crossing, linearly interpolated. NaN if there is no sign change."""
    for lo, hi, v_lo, v_hi in zip(eps_grid, eps_grid[1:], values, values[1:]):
        if v_lo <= 0.0 < v_hi:
            return lo + (hi - lo) * (-v_lo) / (v_hi - v_lo)
    return float("nan")


def main() -> None:
    rng = np.random.default_rng(SEED)
    omega_nat, decay = natural_mode(ETA_T, ETA_L)
    omega_c = 2.0 * omega_nat
    zeta = decay / omega_nat
    h_crit = 4.0 * zeta
    eps_crit_rms = h_crit / np.sqrt(2.0)

    print("=== 0. Operating point and scales ===")
    print(f"  eta_theta={ETA_T}  eta_lambda={ETA_L}")
    print(f"  omega_nat={omega_nat:.6g}  damping sigma=decay/step={decay:.4g}")
    print(f"  zeta={zeta:.5g}  h_crit (peak)={h_crit:.5g}  i.e. in RMS {eps_crit_rms:.5g}")
    print(f"  forcing center band: omega_c=2*omega_nat={omega_c:.6g}")
    print(f"  spectral resolution at T={T_STEPS} steps: {2*np.pi/T_STEPS:.4g} rad/step")
    print(f"  natural bandwidth scale: sigma={decay:.4g} rad/step")

    print()
    print("=== 1. Control: zero modulation, the exponent must fall back to -sigma ===")
    s0 = narrowband(T_STEPS, N_REAL, omega_c, 0.0, rng)
    m0, sd0 = lyapunov(s0, 0.0, 0.0)
    print(f"  measured exponent={m0:+.4e} (+-{sd0:.1e})  expected={-decay:+.4e}")
    print(f"  finite-window bias={m0+decay:+.2e}: the eigenvalues are complex,")
    print("  the norm oscillates and averaging over a non-integer number of periods keeps a")
    print("  residual O(1/T). It shifts thresholds by less than 1%, left visible here.")
    assert abs(m0 + decay) < 1e-5, (m0, -decay)

    print()
    print("=== 2. Control: a single line = sine with random phase, against Floquet ===")
    print("  pure mismatch (eps_theta=0), the single line must reproduce the periodic threshold.")
    print("  eps RMS   eps peak    exponent        verdict")
    grid_line = [0.05, 0.09, 0.13, 0.18, 0.25]
    vals_line = []
    for eps in grid_line:
        m, sd = lyapunov(s0, 0.0, eps)
        vals_line.append(m)
        print(f"  {eps:7.3g}  {eps*np.sqrt(2):9.3g}  {m:+.4e}    {'UNSTABLE' if m > 0 else 'stable'}")
    threshold_line = crossing(grid_line, vals_line)
    print(f"  -> measured RMS threshold={threshold_line:.4g}  expected={eps_crit_rms:.4g}"
          f"  ratio={threshold_line/eps_crit_rms:.3f}")
    assert 0.7 < threshold_line / eps_crit_rms < 1.4, (threshold_line, eps_crit_rms)

    print()
    print("=== 3. Q1: does COHERENT modulation survive broadband forcing? ===")
    print("  eps_theta = eps_lam, band centered on 2*omega_nat, amplitude pushed hard.")
    print("       B/sigma   eps RMS     exponent        verdict")
    bands_coh = [0.0, 1.0, 4.0, 16.0]
    for b_rel in bands_coh:
        s = narrowband(T_STEPS, N_REAL, omega_c, b_rel * decay, rng)
        for eps in (0.3, 0.7):
            m, sd = lyapunov(s, eps, eps)
            print(f"  {b_rel:12.3g}  {eps:8.3g}  {m:+.4e}    "
                  f"{'UNSTABLE' if m > 0 else 'stable'}")
            assert m < 0.0, (b_rel, eps, m)
    print("  -> coherent cancellation is not an artifact of the pure line: the residual")
    print("     forcing of detuned components is itself detuned, and it loses against")
    print("     the damping. No admissible coherent modulation destabilizes.")

    print()
    print("=== 4. Q2: mismatch threshold vs. bandwidth ===")
    print("  eps_theta=0, eps_lam swept. The amplitude criterion should become a")
    print("  spectral-density criterion, so an RMS threshold growing as sqrt(B) for B >> sigma.")
    grid = [0.05, 0.09, 0.13, 0.18, 0.25, 0.35, 0.5, 0.7, 1.0]
    bands = [0.0, 0.5, 2.0, 8.0, 32.0]
    thresholds: list[tuple[float, float]] = []
    for b_rel in bands:
        s = narrowband(T_STEPS, N_REAL, omega_c, b_rel * decay, rng)
        vals = []
        for eps in grid:
            m, _ = lyapunov(s, 0.0, eps)
            vals.append(m)
        thr = crossing(grid, vals)
        thresholds.append((b_rel, thr))
        signs = "".join("+" if v > 0 else "-" for v in vals)
        print(f"  B/sigma={b_rel:6.3g}  signs on the grid [{signs}]  RMS threshold="
              f"{thr:.4g}" + (f"  i.e. {thr/eps_crit_rms:.2f} x the pure-line threshold"
                                if thr == thr else "  (outside range eps<=1)"))
    finite = [(b, s_) for b, s_ in thresholds if s_ == s_ and b > 0.0]
    assert len(finite) >= 4, finite
    print()
    print("  Scaling law. A spectral-density criterion predicts")
    print("    threshold(B) = threshold(line) * sqrt(1 + kappa*B/sigma),")
    print("  with an asymptotic sqrt(B) regime: power must grow with the bandwidth to")
    print("  maintain the density near 2*omega_0. kappa should come out")
    print("  constant over the whole range of bandwidths.")
    print("     B/sigma   threshold/threshold_line   deduced kappa")
    kappas = []
    for b, s_ in finite:
        r = s_ / threshold_line
        k = (r * r - 1.0) / b
        kappas.append(k)
        print(f"  {b:12.3g}  {r:17.3f}  {k:12.3f}")
    k_mean = float(np.mean(kappas))
    spread = (max(kappas) - min(kappas)) / k_mean
    print(f"  -> kappa={k_mean:.3f} +- {np.std(kappas):.3f}, relative spread {spread:.0%}")
    print(f"     over a factor {finite[-1][0]/finite[0][0]:.0f} in bandwidth.")
    assert spread < 0.35, kappas
    print("     Reading: the useful bandwidth is sigma/kappa ="
          f" {1.0/k_mean:.1f}*sigma, i.e. the damping rate itself up to a factor.")
    print("     A coherence non-stationarity shorter than the primal-dual pair's")
    print("     damping time is diluted, not harmless.")
    b_a, b_b = finite[-2][0], finite[-1][0]
    slope = np.log(finite[-1][1] / finite[-2][1]) / np.log(b_b / b_a)
    print(f"  -> asymptotic slope between B/sigma={b_a:.3g} and {b_b:.3g}: {slope:.3f}"
          f" (expected 0.5)")
    assert 0.4 < slope < 0.6, slope

    print()
    print("=== 5. Control: same power, band PLACED ELSEWHERE ===")
    print("  strong mismatch but band outside the neighborhood of 2*omega_nat.")
    eps_strong = 0.5
    for factor in (0.4, 0.7, 1.0, 1.6, 3.0):
        s = narrowband(T_STEPS, N_REAL, factor * omega_c, 2.0 * decay, rng)
        m, _ = lyapunov(s, 0.0, eps_strong)
        marker = "  <- tongue" if abs(factor - 1.0) < 1e-9 else ""
        print(f"  center/2*omega_nat={factor:5.3g}  exponent={m:+.4e}  "
              f"{'UNSTABLE' if m > 0 else 'stable'}{marker}")
    print("  -> the instability remains frequency-selective: it is indeed the parametric")
    print("     resonance, not a generic degradation caused by noise.")

    print()
    print("=== 6. Consequence for (R4): does the broadband threshold still depend on eta_theta? ===")
    print("  The 1/4 law reads again: at B >> sigma, threshold ~ eps_0*sqrt(kappa*B/sigma) with")
    print("  eps_0 = 2*sqrt(2)*zeta and sigma = zeta*omega_0, so threshold ~ sqrt(kappa*B*zeta/omega_0).")
    print("  Now zeta/omega_0 = a/(2*eta_lambda*c^2): eta_theta cancels out. Counter-intuitive")
    print("  prediction to check: at fixed PHYSICAL bandwidth, the threshold no longer")
    print("  depends on eta_theta, whereas in pure-line it collapses as sqrt(eta_theta).")
    b_phys = 4.5e-3
    t6, r6 = 400_000, 8
    print(f"  fixed physical band B={b_phys:.3g} rad/step, T={t6} steps, {r6} realizations")
    print("     eta_theta   r=el/et   sigma      B/sigma   line threshold   band-B threshold   expected band")
    for eta_t in (1e-3, 1e-4):
        w_nat, dec = natural_mode(eta_t, ETA_L)
        z = dec / w_nat
        eps0 = 4.0 * z / np.sqrt(2.0)
        expected = eps0 * np.sqrt(1.0 + k_mean * b_phys / dec)
        # grid calibrated on this configuration's eps_0: the pure-line threshold equals
        # eps_0 by construction, the broadband threshold is a few eps_0.
        grid6 = list(np.geomspace(0.4 * eps0, 10.0 * eps0, 9))
        thresholds6 = []
        for bw in (0.0, b_phys):
            s = narrowband(t6, r6, 2.0 * w_nat, bw, rng)
            vals = [lyapunov(s, 0.0, e, eta_t=eta_t, burn=t6 // 5)[0] for e in grid6]
            thresholds6.append(crossing(grid6, vals))
        print(f"  {eta_t:12.3g}  {ETA_L/eta_t:8.0f}  {dec:.3e}  {b_phys/dec:8.0f}  "
              f"{thresholds6[0]:10.4g}  {thresholds6[1]:14.4g}  {expected:13.4g}")
        if eta_t == 1e-3:
            ref6 = thresholds6
        else:
            ratio_line = ref6[0] / thresholds6[0]
            ratio_band = ref6[1] / thresholds6[1]
            print()
            print(f"  -> ratio of thresholds between the two eta_theta (factor 10):")
            print(f"     pure line   {ratio_line:.2f}  (expected sqrt(10)=3.16, collapse)")
            print(f"     fixed band  {ratio_band:.2f}  (expected ~1, no more dependence)")
            assert 2.5 < ratio_line < 3.9, ratio_line
            assert 0.7 < ratio_band < 1.4, ratio_band
    print("  -> (R4) must be stated with its validity condition. The collapse as")
    print("     sqrt(eta_theta/eta_lambda) is a narrowband statement. At broad band,")
    print("     slowing down the primal shrinks the tongue exactly as much as it reduces")
    print("     the damping: the two effects cancel exactly and the threshold no longer")
    print("     depends on anything but eta_lambda, as 1/sqrt(eta_lambda). The useful lever")
    print("     stays the same (lower eta_lambda, or remove the mismatch), but the case")
    print("     against timescale separation only holds if the non-stationarity is coherent")
    print("     over more than the primal-dual pair's damping time.")

    print()
    print("OK")


if __name__ == "__main__":
    main()
